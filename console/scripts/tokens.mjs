// Turns the design tokens (DTCG JSON in tokens/) into CSS custom properties
// in src/lib/tokens.css. Two layers: brand values shared by both tones and
// the meaning of each color per tone (night, paper). A reference {a.b} becomes
// var(--a-b), so a layer can be overridden in CSS without a rebuild.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../tokens/${name}.json`, import.meta.url)));

function flatten(group, path = [], out = []) {
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith("$")) continue;
    if (node && typeof node === "object" && "$value" in node) {
      out.push([`--${[...path, key].join("-")}`, String(node.$value)]);
    } else if (node && typeof node === "object") {
      flatten(node, [...path, key], out);
    } else {
      throw new Error(`token ${[...path, key].join(".")} has no $value`);
    }
  }
  return out;
}

const names = new Set();
function block(selector, tokens) {
  for (const [name] of tokens) names.add(name);
  const body = tokens.map(([name, value]) => `  ${name}: ${value.replace(/\{([^}]+)\}/g, (_, ref) => `var(--${ref.replaceAll(".", "-")})`)};`);
  return `${selector} {\n${body.join("\n")}\n}\n`;
}

const brand = flatten(read("brand"));
const night = flatten(read("night"));
const paper = flatten(read("paper"));
if (JSON.stringify(night.map(([n]) => n)) !== JSON.stringify(paper.map(([n]) => n))) {
  throw new Error("night and paper must define the same tokens");
}
const css = [
  "/* Generated by scripts/tokens.mjs from tokens/*.json. Do not edit. */\n",
  block(":root", brand),
  block(":root, :root[data-tone=\"night\"]", [["color-scheme", "dark"], ...night]),
  `@media (prefers-color-scheme: light) {\n${block(":root:not([data-tone=\"night\"])", [["color-scheme", "light"], ...paper])}}\n`,
  block(":root[data-tone=\"paper\"]", [["color-scheme", "light"], ...paper]),
].join("\n");

for (const [, value] of [...brand, ...night, ...paper]) {
  for (const [, ref] of value.matchAll(/\{([^}]+)\}/g)) {
    if (!names.has(`--${ref.replaceAll(".", "-")}`)) throw new Error(`unknown token {${ref}}`);
  }
}
writeFileSync(new URL("../src/lib/tokens.css", import.meta.url), css);
